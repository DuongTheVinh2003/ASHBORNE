import {readFile,writeFile} from 'node:fs/promises';
const read=name=>readFile(new URL(name,import.meta.url),'utf8');
let three=await read('vendor/three.module.js');
three=three.replace(/export \{([^}]+)\};\s*$/, 'return {$1};');
let siege=await read('siege.mjs');
const siegeNames=[...siege.matchAll(/export (?:const|function) (\w+)/g)].map(m=>m[1]);
siege=siege.replace(/export (?=const|function)/g,'');
let game=await read('game.mjs');
const names=[...game.matchAll(/export (?:const|function) (\w+)/g)].map(m=>m[1]);
game=game.replace(/export (?=const|function)/g,'').replace("import * as Siege from './siege.mjs';",'const Siege=SIEGE_BUNDLED;');
let world=await read('world.mjs');
world=world.replace(/^import .* from '.\/game.mjs';/m, 'const {CASTLES,UNITS,FIELD,defense,cellPosition,survivors}=G;').replace('export class World','class World').replace("await import('./vendor/three.module.js')",'THREE_BUNDLED');
let app=await read('app.mjs');
app=app.replace("import * as G from './game.mjs';",'').replace("import {World} from './world.mjs';",'');
const script=`const THREE_BUNDLED=(()=>{${three}\n})();\nconst SIEGE_BUNDLED=(()=>{${siege}\nreturn {${siegeNames.join(',')}};})();\nconst G=(()=>{${game}\nreturn {${names.join(',')}};})();\n${world}\n${app}`;
let html=await read('index.html');
html=html.replace('<link rel="stylesheet" href="style.css">','<style></style>');
const css=await read('style.css');html=html.replace('<style></style>',()=>`<style>${css}</style>`);
const license=await read('vendor/LICENSE');
html=html.replace('<script type="module" src="app.mjs"></script>',()=>`<!-- Three.js license\n${license}\n--><script type="module">\n${script.replace(/<\/script/gi,'<\\/script')}\n</script>`);
await writeFile(new URL('dist/index.html',import.meta.url),html);
console.log('Built prototype-v2/dist/index.html — standalone 2D game.');
